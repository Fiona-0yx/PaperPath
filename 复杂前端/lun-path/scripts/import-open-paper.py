"""Refresh the single PLOS ONE open-access reading sample."""

import json
import sys
from pathlib import Path
from urllib.parse import quote
from urllib.request import urlopen
from xml.etree import ElementTree as ET

DOI = "10.1371/journal.pone.0316019"
SOURCE = "https://journals.plos.org/plosone/article/file?id=" + quote(DOI, safe="") + "&type=manuscript"
LICENSE = "https://creativecommons.org/licenses/by/4.0/"
HREF = "{http://www.w3.org/1999/xlink}href"


def plain_text(element):
    parts = [element.text or ""]
    for child in element:
        if child.tag in {"inline-formula", "disp-formula"}:
            parts.append(" [formula in original] ")
        elif child.tag not in {"fig", "table-wrap", "supplementary-material"}:
            parts.append(plain_text(child))
        parts.append(child.tail or "")
    return "".join(parts)


def text(element):
    return " ".join(plain_text(element).split())


def extract_sections(node, sections):
    title = node.find("title")
    heading = text(title) if title is not None else "Abstract"
    paragraphs = [text(p) for p in node.findall("p")]
    paragraphs = [p for p in paragraphs if p]
    if paragraphs:
        sections.append({"id": node.get("id", "abstract"), "heading": heading, "paragraphs": paragraphs})
    for section in node.findall("sec"):
        extract_sections(section, sections)


def main():
    if len(sys.argv) == 2:
        xml = Path(sys.argv[1]).read_bytes()
    else:
        with urlopen(SOURCE, timeout=20) as response:
            xml = response.read(1_000_001)
    if len(xml) > 1_000_000:
        raise ValueError("The source XML exceeds one MB")
    article = ET.fromstring(xml)
    meta = article.find("./front/article-meta")
    if meta.findtext("article-id[@pub-id-type='doi']") != DOI:
        raise ValueError("Unexpected paper DOI")
    license_url = meta.find("./permissions/license").get(HREF, "").replace("http://", "https://", 1)
    if license_url != LICENSE:
        raise ValueError("The source does not declare the expected CC BY 4.0 license")
    abstract = meta.find("abstract")
    sections = []
    extract_sections(abstract, sections)
    for section in article.findall("./body/sec"):
        if section.get("sec-type") != "supplementary-material":
            extract_sections(section, sections)
    if len(sections) < 3:
        raise ValueError("The source did not contain the expected reading material")
    authors = [
        " ".join(filter(None, [name.findtext("given-names"), name.findtext("surname")]))
        for name in meta.findall("./contrib-group/contrib[@contrib-type='author']/name")
    ]
    paper = {
        "id": "plos-roc-auc",
        "version": "v1",
        "categoryId": "machine-learning",
        "title": text(meta.find("./title-group/article-title")),
        "language": "英文",
        "difficulty": 2,
        "authors": authors,
        "year": 2024,
        "venue": "PLOS ONE",
        "doi": DOI,
        "original": "https://doi.org/" + DOI,
        "licenseUrl": LICENSE,
        "materialKind": "open-text",
        "abstract": text(abstract),
        "sections": sections,
    }
    target = Path(__file__).resolve().parents[1] / "shared" / "open-paper.js"
    snapshot = (
        "// Generated by scripts/import-open-paper.py from the licensed PLOS JATS source.\n"
        "export const openPaper = " + json.dumps(paper, ensure_ascii=False, indent=2) + ";\n"
    )
    target.write_text(snapshot, encoding="utf-8")
    print(f"{paper['id']}: {len(sections)} sections, {sum(len(s['paragraphs']) for s in sections)} paragraphs")


if __name__ == "__main__":
    main()
