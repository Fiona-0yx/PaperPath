  check(await b.evaluate("document.querySelector('#grove-frame').contentWindow.__groveIdentity==='same-world'"),'welcome and learning garden retain the same live scene');
  await b.shot('grove-garden-desktop');
  await nativeClick('.card--about');await b.until("location.hash==='#/shelf/methods'");
  check(await b.evaluate("!!document.querySelector('#shelf-frame')"),'method branch opens its existing paper shelf');
  await b.evaluate("location.hash='#/garden'");await ready();await b.delay(1100);
  await nativeClick('.liquid-button--play');await b.until("location.hash==='#/shelf/foundations'");
  check(true,'foundation branch opens its own shelf');
  await b.evaluate("location.hash='#/home'");await ready();await b.delay(500);
  await b.click('[data-lang="en"]');await b.until("document.querySelector('#grove-frame').contentDocument.documentElement.lang==='en'");
